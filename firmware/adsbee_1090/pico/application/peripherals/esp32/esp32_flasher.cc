#define BIN_FIRST_SEGMENT_OFFSET 0x18
// Maximum block sized for RAM and Flash writes, respectively.
#define ESP_RAM_BLOCK            0x1800

// For esp8266, esp32, esp32s2
#define BOOTLOADER_ADDRESS_V0    0x1000
