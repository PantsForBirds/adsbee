/**
 * @brief esptool portable bin header format
 */
typedef struct esp_bin_header {
    uint8_t magic;
    uint8_t segments;
    uint8_t flash_mode;
    uint8_t flash_size_freq;
    uint32_t entrypoint;
} esp_bin_header_t;

/**
 * @brief esptool portable bin segment format
 */
typedef struct esp_bin_segment {
    uint32_t addr;
    uint32_t size;
    uint8_t *data;
} esp_bin_segment_t;

