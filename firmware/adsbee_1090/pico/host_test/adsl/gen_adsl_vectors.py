"""Writes adsl_vectors.hh from adsl_vectors.json (ADS-L golden vectors from the Bee Waggler's adsl_ref.py).

Usage: python3 gen_adsl_vectors.py  (run from this directory)
"""
import json

d = json.load(open('adsl_vectors.json'))


def num(x):
    return 'NAN' if x is None else repr(float(x)) + 'f'


lines = ['// Generated by gen_adsl_vectors.py from adsl_vectors.json. Do not edit.', '#pragma once', '',
         '#include <cmath>', '#include <cstdint>', '', 'struct ADSLGoldenVector {',
         '    const char *name;', '    const char *packet_hex;  // Length byte .. CRC.',
         '    const char *chips_hex;   // Whole burst: preamble, sync, packet.', '    uint16_t num_chips;',
         '    bool crc_ok;', '    uint8_t payload_type;', '    uint8_t amt;', '    uint32_t address;',
         '    uint8_t version;', '    uint8_t key_index;', '    const char *adsl_data_clear_hex;',
         '    // Traffic: decoded values, NAN when invalid.', '    float lat, lon, alt_m, gs_mps, vrate_mps, track_deg;',
         '    // Traffic: raw fields.', '    int ts_qs, flight_state, category, emergency, sil, sda, nic, hfom, vfom, vacc;',
         '    // Status.', '    int max_version, rx_m, rx_o_ldr, rx_o_hdr, mobile, econ_rx, econ_tx, xpdr, uplink_client,'
         ' fisb_client;', '};', '', 'static const ADSLGoldenVector kADSLGoldenVectors[] = {']
for v in d['vectors']:
    f = v.get('fields', {})
    dec = v.get('decoded', {})
    t = v['payload_type'] == 2
    vals = [num(dec.get(k)) if t else 'NAN' for k in ('lat', 'lon', 'alt', 'gs', 'vrate', 'track')]
    tr = [str(f.get(k, 0)) if t else '0' for k in
          ('ts_qs', 'flight_state', 'category', 'emergency', 'sil', 'sda', 'nic', 'hfom', 'vfom', 'vacc')]
    st = [str(f.get(k, 0)) if not t else '0' for k in
          ('max_version', 'rx_m', 'rx_o_ldr', 'rx_o_hdr', 'mobile', 'econ_rx', 'econ_tx', 'xpdr', 'uplink_client',
           'fisb_client')]
    lines.append('    {"%s", "%s", "%s", %d, %s, %d, %d, 0x%s, %d, %d, "%s", %s, %s, %s},' % (
        v['name'], v['packet'], v['chips_hex'], v['n_chips'], 'true' if v.get('crc_ok', True) else 'false',
        v['payload_type'], v['amt'], v['address'], v['version'], v['key_index'], v['adsl_data_clear'],
        ', '.join(vals), ', '.join(tr), ', '.join(st)))
lines += ['};', '']
open('adsl_vectors.hh', 'w').write('\n'.join(lines))
